#!/usr/bin/env python3
"""
Independent re-analysis of the open-loop re-run (Gemini-flagged: the original campaign's
500-Locust-user generator is closed-loop, coupling offered rate to response time, which confounds
goodput/capacity comparisons across policies). Reuses analyze.py's exact window definitions,
outcome classification (GOOD/REJECT/FAIL) and per-run metric functions -- this script only changes
which directories are read from and adds an explicit check that every policy really was offered the
same load, which is the property the whole re-run exists to establish.

Reads results/<scenario>__openloop/<policy>/rep*/ (chain) and results/<scenario>-split__openloop/...
(split); writes results/analysis/openloop_per_run_metrics.csv and openloop_summary_metrics.csv,
plus an offered-load parity check printed to stdout.
"""
import glob, os, sys
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze import load_run, window, SCEN, ROOT, OUT  # noqa: E402

# Optional: analyze_openloop.py [results_root [out_dir]] -- used for the 5-repetition instrumented re-run, whose
# runs sit in a separate directory tree with the same layout. Defaults are the campaign's own directories.
if __name__ == "__main__" and len(sys.argv) > 1:
    ROOT = sys.argv[1]
    OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "analysis")
    os.makedirs(OUT, exist_ok=True)


# Event clock (correction, 2026-11-20). analyze.load_run() puts t = 0 at the first telemetry sample, i.e. on the
# benchmark VM's clock, which is the clock the server-side fault injector uses (faults start at t = 60 s on it).
# The flash crowd, however, is generated by the open-loop generator on the load-generator VM, which starts its own
# schedule several seconds earlier (8 s in the original campaign, 15 s in the re-run), so on the telemetry clock the
# flash ran at roughly 52-72 s, not 60-80 s. And the issue-time cohort below took t = 0 at the first *completed
# request*, which is the generator's clock, so for the server-injected faults its 60-105 s / 60-80 s windows were
# shifted by the same offset. Both windows are now taken on the clock of the event they measure:
#   spike (generator-side) -> t = 0 at the generator's first issue;
#   lock, gc, hang (server-side) -> t = 0 at the first telemetry sample, exactly as load_run()/window() use.
def load_run_aligned(d, scen):
    lr = load_run(d)
    if lr is None or scen != "spike":
        return lr
    r, t = lr
    r["t"] = (r.ts_ms - r.issued_ts_ms.min()) / 1000.0
    return r, t


def event_t0(reqrows, d, scen):
    if scen == "spike":
        return min(float(r["issued_ts_ms"]) for r in reqrows)
    return float(pd.read_csv(f"{d}/telemetry.csv", usecols=["ts_ms"]).ts_ms.min())

POLICIES = ["none", "static", "static-aggr", "resilience4j", "gradient", "concurrency-limits", "adaptive"]
SPLIT_POLICIES = ["none", "static", "static-aggr", "gradient", "adaptive"]
SPLIT_SCENARIOS = ["lock", "gc"]


def offered_load_parity_check():
    """The property this whole re-run exists to establish: every policy sees the same offered
    count (arrival trace is identical across policies for a given scenario+rep, by construction)."""
    print("=== Offered-load parity check (max relative spread within scenario+rep, across policies) ===")
    worst = 0.0
    for scen in SCEN:
        for topology, pols, suffix in [("chain", POLICIES, ""), ("split", SPLIT_POLICIES, "-split")]:
            if topology == "split" and scen not in SPLIT_SCENARIOS:
                continue
            for rep in range(10):
                counts = []
                for pol in pols:
                    f = f"{ROOT}/{scen}{suffix}__openloop/{pol}/rep{rep}/requests.csv"
                    if os.path.exists(f):
                        with open(f) as fh:
                            counts.append(sum(1 for _ in fh) - 1)
                if len(counts) > 1:
                    spread = (max(counts) - min(counts)) / max(counts)
                    worst = max(worst, spread)
    print(f"worst-case relative spread in offered count across policies, any scenario/topology/rep: {worst:.4%}")
    return worst


EVENT_WINDOWS = {"spike": (60, 80), "lock": (60, 105), "gc": (60, 105), "hang": (60, 80)}


def issue_cohort_metrics():
    """Corrects a real bug: window()/load_run() bin every request by COMPLETION time, so a request
    issued during the fault but completed after it (because the policy queued it a long time) is
    silently counted in the RECOVERY window instead of the EVENT window -- this systematically
    understates a slow policy's true event-window success count and was caught by an external
    review. This instead cohorts every request by ISSUE time and tracks it to its eventual outcome
    regardless of when that outcome lands, which is the only way to fairly compare "how much of the
    load offered during the fault did each policy eventually succeed at" across policies with very
    different latencies."""
    rows = []
    for scen, (a, b) in EVENT_WINDOWS.items():
        for topology, pols, suffix in [("chain", POLICIES, ""), ("split", SPLIT_POLICIES, "-split")]:
            if topology == "split" and scen not in SPLIT_SCENARIOS:
                continue
            for pol in pols:
                tot_n = tot_good = tot_rej = tot_fail = tot_incomplete = nrep = 0
                for f in sorted(glob.glob(f"{ROOT}/{scen}{suffix}__openloop/{pol}/rep[0-9]*/requests.csv")):
                    with open(f) as fh:
                        reqrows = list(__import__("csv").DictReader(fh))
                    if not reqrows:
                        continue
                    t0 = event_t0(reqrows, os.path.dirname(f), scen)
                    nrep += 1
                    cohort = [r for r in reqrows if a <= (float(r["issued_ts_ms"]) - t0) / 1000 < b]
                    tot_n += len(cohort)
                    tot_good += sum(1 for r in cohort if r["outcome"] in ("ok", "not_found"))
                    tot_rej += sum(1 for r in cohort if r["outcome"] in ("shed", "shed_route", "breaker_open", "breaker_half_open"))
                    tot_fail += sum(1 for r in cohort if r["outcome"] in ("timeout", "downstream_error", "client_error"))
                    tot_incomplete += sum(1 for r in cohort if not r["completed_ts_ms"])
                if tot_n == 0:
                    continue
                dur = (b - a) * nrep  # seconds of event window summed over the repetitions present
                rows.append({"scenario": scen, "topology": topology, "policy": pol, "reps": nrep,
                             "issued": tot_n, "eventual_success": tot_good,
                             "eventual_success_rps": tot_good / dur,
                             "rejected": tot_rej, "failed": tot_fail, "still_incomplete": tot_incomplete})
    df = pd.DataFrame(rows)
    df.to_csv(f"{OUT}/openloop_issue_cohort.csv", index=False)
    return df


def run():
    rows = []
    for scen, (title, ev, rec) in SCEN.items():
        for topology, pols, suffix in [("chain", POLICIES, ""), ("split", SPLIT_POLICIES, "-split")]:
            if topology == "split" and scen not in SPLIT_SCENARIOS:
                continue
            for pol in pols:
                for d in sorted(glob.glob(f"{ROOT}/{scen}{suffix}__openloop/{pol}/rep[0-9]*")):
                    lr = load_run_aligned(d, scen)
                    if lr is None:
                        continue
                    r, t = lr
                    if r.t.max() < 140:
                        print("skipping short run", d)
                        continue
                    base = window(r, 20, 58)
                    evw = window(r, *ev)
                    recw = window(r, *rec)
                    row = {"scenario": scen, "topology": topology, "policy": pol, "rep": os.path.basename(d)}
                    row.update({f"base_{k}": v for k, v in base.items()})
                    row.update({f"event_{k}": v for k, v in evw.items()})
                    row.update({f"rec_{k}": v for k, v in recw.items()})
                    rows.append(row)
    df = pd.DataFrame(rows)
    df.to_csv(f"{OUT}/openloop_per_run_metrics.csv", index=False)
    agg = df.drop(columns=["rep"]).groupby(["scenario", "topology", "policy"]).agg(["mean", "std", "count"])
    agg.columns = ["_".join(c) for c in agg.columns]
    agg = agg.reset_index()
    agg.to_csv(f"{OUT}/openloop_summary_metrics.csv", index=False)
    return df, agg


def latency_split():
    """Only for runs whose generator recorded sent_ts_ms (the re-run): split each successful request's latency into
    issued -> sent (waiting in the generator for one of its in-flight slots) and sent -> completed (network and
    server). Windows and clocks as in run(); per-rep percentiles averaged over reps, like every latency cell."""
    rows, per_run = [], []
    for scen, (title, ev, rec) in SCEN.items():
        for topology, pols, suffix in [("chain", POLICIES, ""), ("split", SPLIT_POLICIES, "-split")]:
            if topology == "split" and scen not in SPLIT_SCENARIOS:
                continue
            for pol in pols:
                per = {"base": [], "event": []}
                for d in sorted(glob.glob(f"{ROOT}/{scen}{suffix}__openloop/{pol}/rep[0-9]*")):
                    lr = load_run_aligned(d, scen)
                    if lr is None or "sent_ts_ms" not in lr[0].columns:
                        continue
                    r = lr[0]
                    ok = r[r.good & r.sent_ts_ms.notna()]
                    for p, (a, b) in (("base", (20, 58)), ("event", ev)):
                        w = ok[(ok.t >= a) & (ok.t < b)]
                        if len(w):
                            x = pd.DataFrame({"q": w.sent_ts_ms - w.issued_ts_ms,
                                              "s": w.completed_ts_ms - w.sent_ts_ms, "l": w.latency_ms})
                            per[p].append(x)
                            per_run.append({"scenario": scen, "topology": topology, "policy": pol,
                                            "rep": os.path.basename(d), "window": p, "n_ok": len(x),
                                            "queued_p50_ms": x.q.median(), "server_p50_ms": x.s.median(),
                                            "queued_share_pct": 100 * x.q.sum() / x.l.sum()})
                for p, xs in per.items():
                    if not xs:
                        continue
                    avg = lambda c, q: sum(x[c].quantile(q) for x in xs) / len(xs)
                    rows.append({"scenario": scen, "topology": topology, "policy": pol, "window": p, "reps": len(xs),
                                 "latency_p50_ms": avg("l", .5), "queued_p50_ms": avg("q", .5),
                                 "server_p50_ms": avg("s", .5), "latency_p99_ms": avg("l", .99),
                                 "queued_p99_ms": avg("q", .99), "server_p99_ms": avg("s", .99),
                                 "queued_share_pct": sum(100 * x.q.sum() / x.l.sum() for x in xs) / len(xs)})
    df = pd.DataFrame(rows)
    if len(df):
        df.to_csv(f"{OUT}/openloop_latency_split.csv", index=False)
        pd.DataFrame(per_run).to_csv(f"{OUT}/openloop_latency_split_per_run.csv", index=False)
    return df


if __name__ == "__main__":
    import json
    spread = offered_load_parity_check()
    df, agg = run()
    cohort_df = issue_cohort_metrics()
    latency_split()
    print("\n=== Issue-time cohort (corrects the completion-time-window bug) ===")
    print(cohort_df.to_string(index=False))
    # how far the generator's clock leads the server's (first issue -> first telemetry sample), median over runs
    leads = []
    for d in glob.glob(f"{ROOT}/*__openloop/*/rep[0-9]*"):
        try:
            gi = pd.read_csv(f"{d}/requests.csv", usecols=["issued_ts_ms"]).issued_ts_ms.min()
            tt = pd.read_csv(f"{d}/telemetry.csv", usecols=["ts_ms"]).ts_ms.min()
            leads.append((tt - gi) / 1000.0)
        except Exception:
            pass
    json.dump({"offered_load_parity_pct": spread * 100, "n_runs": len(df),
               "generator_lead_s_median": float(pd.Series(leads).median()),
               "generator_lead_s_min": float(min(leads)), "generator_lead_s_max": float(max(leads))},
              open(f"{OUT}/openloop_scalars.json", "w"))
    print(f"\n{len(df)} runs analyzed")
    print("\n=== Goodput comparison (event window), chain topology ===")
    for scen in SCEN:
        sub = agg[(agg.scenario == scen) & (agg.topology == "chain")]
        print(f"\n{scen}:")
        for _, row in sub.iterrows():
            print(f"  {row['policy']:20s} base_goodput={row['base_goodput_rps_mean']:7.1f}  "
                  f"event_goodput={row['event_goodput_rps_mean']:7.1f}  event_p99={row['event_p99_ms_mean']:8.1f}ms  "
                  f"reject%={row['event_reject_pct_mean']:5.1f}  fail%={row['event_fail_pct_mean']:5.1f}")
